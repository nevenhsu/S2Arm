"""Generate the Vulkan 1.1 D24 readback shader header."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile

here = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument("--glslang", default="glslangValidator")
args = parser.parse_args()
build = here.parents[3] / "build"
build.mkdir(exist_ok=True)
with tempfile.TemporaryDirectory(dir=build) as temp:
    binary = Path(temp) / "pack.spv"
    subprocess.run(
        [args.glslang, "--target-env", "vulkan1.1", "-V", "-Os", str(here / "pack.comp"), "-o", str(binary)],
        check=True,
    )
    subprocess.run(["spirv-val", "--target-env", "vulkan1.1", str(binary)], check=True)
    words = [word for (word,) in struct.iter_unpack("<I", binary.read_bytes())]

lines = [
    "// SPDX-License-Identifier: Apache-2.0",
    "// Generated by d24_readback_shaders/generate.py (Vulkan 1.1).",
    "#pragma once",
    "#include <stdint.h>",
    "static const uint32_t nvk_d24_readback_spv[] = {",
]
for i in range(0, len(words), 8):
    lines.append("    " + ", ".join(f"0x{word:08x}u" for word in words[i:i + 8]) + ",")
lines += ["};", ""]
(here.parent / "backend_vulkan_d24_readback_spv.h").write_text("\n".join(lines))
